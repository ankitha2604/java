package ankitha;

public class datatype {

	public static void main(String[] args) {
		byte b = 100;
		char c = 'a';
	
        long l = 200l;
        short s1 = 300;
        float f = 400.0f;
        double d = 500.5d;
        int i =600;
        
        System.out.println(+b);
        System.out.println(+c);
       
        System.out.println(+l);
        System.out.println(+s1);
        System.out.println(+f);
        System.out.println(+d);
        System.out.println(+i);
	}

}
